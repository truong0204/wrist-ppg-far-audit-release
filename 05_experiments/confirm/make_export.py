def f(x, d=2):
    if x is None:
        return "—"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, (int, float)):
        if x != x:
            return "NaN"
        if abs(x) < 0.5 * 10 ** -d:
            x = 0.0
        return f"{x:.{d}f}"
    return str(x)


def ci(v, d=2):
    return "—" if not v else f"[{f(v[0], d)}, {f(v[1], d)}]"


def table(head, rows):
    esc = lambda c: str(c).replace("|", "\\|")
    w("| " + " | ".join(esc(h) for h in head) + " |")
    w("|" + "---|" * len(head))
    for row in rows:
        w("| " + " | ".join(esc(c) for c in row) + " |")
    w("")


