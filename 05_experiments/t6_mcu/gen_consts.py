"""T6 step 2: generate the constant tables of the C core (06_firmware/h32_e2/main/h32_consts.h) and the model array
(model_data.c) from the frozen Python pipeline (features.py, e2cnn.py, method.py, confirm.py) and the INT8 model.
Nothing is fitted here; every number is copied from the pipeline.
    uv run python -W ignore 05_experiments/t6_mcu/gen_consts.py
"""
import json, pathlib, sys
import numpy as np
from scipy.signal import butter, sosfilt_zi

ROOT = pathlib.Path(__file__).resolve().parents[2]; sys.path.insert(0, str(ROOT / "04_code"))
from h32 import e2cnn, features, method as M, confirm  # noqa: E402

MAIN = ROOT / "06_firmware/h32_e2/main"; MAIN.mkdir(parents=True, exist_ok=True)
meta = json.load(open(ROOT / "05_experiments/t6_mcu/model/quant_meta.json"))
L = []; w = L.append


def arr(name, a, ctype, fmt="{:.9e}"):
    a = np.asarray(a).ravel(); vals = ", ".join((fmt.format(float(v)) + ("f" if ctype == "float" else "")) if ctype in ("float", "double") else str(int(v)) for v in a)
    w(f"static const {ctype} {name}[{len(a)}] = {{{vals}}};")


w("/* generated by 05_experiments/t6_mcu/gen_consts.py from the frozen Python pipeline; do not edit */")
w("#pragma once\n#include <stdint.h>")
for tag, fs, nwin, nfft in (("PPG", 64, 512, 2048), ("ACC", 32, 256, 1024)):
    sos = butter(4, (0.5, 4.0), btype="band", fs=fs, output="sos")
    ntaps = 2 * len(sos) + 1 - min((sos[:, 2] == 0).sum(), (sos[:, 5] == 0).sum()); edge = 3 * ntaps
    f = np.fft.rfftfreq(nfft, 1.0 / fs); idx = np.clip(np.searchsorted(f, features.FQ), 1, len(f) - 1)
    lo = f[idx - 1]; t = (features.FQ - lo) / (f[idx] - lo)
    w(f"#define H32_{tag}_NSEC {len(sos)}\n#define H32_{tag}_EDGE {edge}\n#define H32_{tag}_NFFT {nfft}\n#define H32_{tag}_NWIN {nwin}")
    w(f"#define H32_{tag}_NBIN_MAX {int(idx.max()) + 1}")
    arr(f"H32_{tag}_SOS", sos, "double", "{:.17e}")           # b0 b1 b2 a0 a1 a2 per section
    arr(f"H32_{tag}_ZI", sosfilt_zi(sos), "double", "{:.17e}")
    arr(f"H32_{tag}_IIDX", idx, "int16_t"); arr(f"H32_{tag}_IT", t, "float")
mask = e2cnn.FCN_MASK; mi = np.flatnonzero(mask)
step = float(np.mean(np.diff(e2cnn.FCN_GRID))); d = np.arange(-40, 41) * step
k = np.exp(-0.5 * (d / 3.0) ** 2); k /= k.sum()
w(f"#define H32_NB {len(mi)}\n#define H32_HMM_HALF 40\n#define H32_HMM_FLOOR 1e-3f\n#define H32_P_EPS 1e-6f")
arr("H32_MASK_IDX", mi, "int16_t"); arr("H32_GRID", e2cnn.FCN_GRID, "float"); arr("H32_HMM_K", k, "float")
w(f"#define H32_THETA {confirm.TH!r}\n#define H32_LW {M.LW}\n#define H32_EDGE0 {M.STATE_EDGES[0]!r}\n#define H32_EDGE1 {M.STATE_EDGES[1]!r}")
w(f"#define H32_NCAL {confirm.N_CAL}\n#define H32_K_FIRST {confirm.FIRST_TEST['K']}\n#define H32_R_FIRST {confirm.FIRST_TEST['R']}")
assert list(confirm.LAGS["R"]) == [2, 3, 4, 5, 6, 7]
w(f"#define H32_IN_SCALE {meta['input']['scale']!r}\n#define H32_IN_ZP ({meta['input']['zero_point']})")
w(f"#define H32_OUT_SCALE {meta['output']['scale']!r}f\n#define H32_OUT_ZP ({meta['output']['zero_point']})")
(MAIN / "h32_consts.h").write_text("\n".join(L) + "\n")

VARIANT = sys.argv[1] if len(sys.argv) > 1 else "dense"            # amendment 1: the board runs the dense model
MODEL = {"orig": "specfcn_seed0_int8.tflite", "dense": "specfcn_seed0_int8_dense.tflite"}[VARIANT]
b = (ROOT / "05_experiments/t6_mcu/model" / MODEL).read_bytes()
rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 16]) for i in range(0, len(b), 16)]
(MAIN / "model_data.c").write_text(f"/* generated by gen_consts.py from model/{MODEL} */\n#include <stdint.h>\n"
                                   f"const unsigned int h32_model_len = {len(b)};\n"
                                   "__attribute__((aligned(16))) const uint8_t h32_model[] = {\n" + ",\n".join(rows) + "\n};\n")
print("consts + model", MODEL, len(b), "bytes; NB", len(mi), "edges", [3 * (2 * 4 + 1)])
