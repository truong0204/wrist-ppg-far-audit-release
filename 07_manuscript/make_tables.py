def table(name, spec, head, rows, caption, label, size=r"\footnotesize", env="tabular", width=None, notes=None):
    L = [f"% generated by 07_manuscript/make_tables.py ({name})", r"\begin{table}[htbp]", r"\centering", size,
         f"\\caption{{{caption}}}\\label{{{label}}}",
         (f"\\begin{{tabularx}}{{{width}}}{{{spec}}}" if env == "tabularx" else f"\\begin{{tabular}}{{{spec}}}"),
         r"\toprule", " & ".join(head) + r" \\", r"\midrule"]
    L += [" & ".join(r) + r" \\" for r in rows]
    L += [r"\bottomrule", r"\end{tabularx}" if env == "tabularx" else r"\end{tabular}"]
    if notes:
        L += [r"\par\smallskip\begin{minipage}{0.95\linewidth}\scriptsize " + notes + r"\end{minipage}"]
    L += [r"\end{table}"]
    (OUT / f"{name}.tex").write_text("\n".join(L) + "\n")

