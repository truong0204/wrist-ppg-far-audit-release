def md_tables(text):
    out = []
    for m in re.finditer(r"((?:^\|.*\|\n)+)", text, re.M):
        lines = [l for l in m.group(1).strip().splitlines() if not re.match(r"^\|[-| ]+\|$", l)]
        out.append([[c.strip() for c in l.strip().strip("|").split("|")] for l in lines])
    return out


