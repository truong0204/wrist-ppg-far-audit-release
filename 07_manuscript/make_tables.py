def tex(s):
    s = str(s)
    codes = []
    def keep(m):                                  # inline code -> breakable \nolinkurl, protected from escaping
        c = m.group(1)
        if re.search(r"[%#{}\\^~]", c):
            return m.group(0)
        codes.append(c); return f"\x00{len(codes) - 1}\x00"
    s = re.sub(r"`([^`]+)`", keep, s)
    for a, b in REP:
        s = s.replace(a, b)
    s = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", s)
    s = re.sub(r"`([^`]+)`", r"\\texttt{\1}", s)
    s = re.sub("\x00(\\d+)\x00", lambda m: "\\nolinkurl{" + codes[int(m.group(1))] + "}", s)
    s = re.sub(r'(^|(?<=[\s(\[]))"', '``', s); s = s.replace('"', "''")
    s = re.sub(r"(?<=[\s(\[`])'(?=\w)", "`", s)              # opening single quote of a nested quotation (PI, D2)
    s = s.replace("'''", r"'\,''")                             # inner closing ' followed by outer closing ''
    return s


